// Builds ONE self-contained index.ts per Edge Function (supabase/functions-bundled/<fn>/index.ts).
// For manual Dashboard deploys: paste a single file instead of four (a stale/mismatched store.ts or handler.ts
// in a multi-file paste was the BootFailure class we hit in Production). Requires `deno` (devDependency).
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DENO = spawnSync(join(ROOT, "node_modules/.bin/deno"), ["--version"]).status === 0 ? join(ROOT, "node_modules/.bin/deno") : "deno";
for (const fn of ["invite-student", "delete-student", "ai-variant"]) {
  const tmp = join(ROOT, "node_modules/.cache", `${fn}.js`);
  mkdirSync(dirname(tmp), { recursive: true });
  const r = spawnSync(DENO, ["bundle", "--platform", "deno", "--external", "npm:*", "-o", tmp, join(ROOT, "supabase/functions", fn, "index.ts")], { encoding: "utf8" });
  if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
  const outDir = join(ROOT, "supabase/functions-bundled", fn);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "index.ts"),
    `// GENERATED by scripts/build-edge-bundles.mjs from supabase/functions/${fn}/ — do not edit; paste this single file in the Dashboard.\n${readFileSync(tmp, "utf8")}`);
  console.log("built", fn);
}
